#!/usr/bin/env python3
"""
Writes libs.json: the third-party libraries hpclib's pages load from a CDN, each at an exact version, with the
sha384 of every file the page loads. A maintainer runs this after changing a version in LIBS below:

    python3 hpclib/ui/update_libs.py            # fetch each package from the npm registry, hash its files
    python3 hpclib/ui/update_libs.py --check    # exit 1 when libs.json isn't what LIBS and the registry give

The hashes are of the files as the npm package ships them, which is what jsDelivr serves for a path that doesn't
say .min.js, so a script tag with `integrity` and `crossorigin` accepts it. A page that loads a library from some
other mirror (a site's own npm proxy) leaves the hashes out, since that mirror may serve other bytes.

Standard library only.
"""
import base64
import hashlib
import io
import json
import os
import sys
import tarfile
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REGISTRY = os.environ.get("NPM_REGISTRY", "https://registry.npmjs.org")

# name: the package, its exact version, what a page loads first (styles, then scripts: in order), what it loads
# after those (together; one that fails to load is left out), the global the scripts define, and what it needs
LIBS = {
    "codemirror": {
        "package": "codemirror", "version": "6 (bundled)", "global": "CM6", "local": "vendor/codemirror6.js",
        "needsBuild": "vendor/_build/build.sh",
    },
    "xterm": {
        "package": "@xterm/xterm", "version": "6.0.0", "global": "Terminal",
        "styles": ["css/xterm.css"], "scripts": ["lib/xterm.js"], "needs": ["xterm-fit"], "wants": ["xterm-web-links"],
    },
    "wunderbaum": {
        "package": "wunderbaum", "version": "0.14.1", "global": "mar10",
        "styles": ["dist/wunderbaum.css"], "scripts": ["dist/wunderbaum.umd.min.js"],
    },
    "xterm-fit": {"package": "@xterm/addon-fit", "version": "0.11.0", "global": "FitAddon", "scripts": ["lib/addon-fit.js"]},
    "xterm-web-links": {"package": "@xterm/addon-web-links", "version": "0.12.0", "global": "WebLinksAddon",
                        "scripts": ["lib/addon-web-links.js"]},
}


def fetch(url):
    with urllib.request.urlopen(url, timeout=120) as res:
        return res.read()


def package_files(package, version):
    """{path inside the package: bytes} of the npm tarball."""
    name = package.split("/")[-1]
    data = fetch("%s/%s/-/%s-%s.tgz" % (REGISTRY, package, name, version))
    out = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            if member.isfile():
                out[member.name.split("/", 1)[1]] = tar.extractfile(member).read()
    return out


def sri(data):
    return "sha384-" + base64.b64encode(hashlib.sha384(data).digest()).decode()


def build():
    out = {"_about": "Generated by update_libs.py: exact versions and the sha384 of each file a page loads."}
    for name, spec in LIBS.items():
        if spec.get("local"):   # a bundle that ships in this directory (vendor/_build/build.sh): hash the file as it is
            with open(os.path.join(HERE, spec["local"]), "rb") as f:
                entry = {k: v for k, v in spec.items() if k != "needsBuild"}
                entry["integrity"] = {spec["local"]: sri(f.read())}
            out[name] = entry
            continue
        files = package_files(spec["package"], spec["version"])
        wanted = spec.get("styles", []) + spec.get("scripts", []) + spec.get("after", [])
        missing = [f for f in wanted if f not in files]
        if missing:
            raise SystemExit("%s@%s has no %s" % (spec["package"], spec["version"], ", ".join(missing)))
        entry = dict(spec)
        entry["integrity"] = {f: sri(files[f]) for f in wanted}
        out[name] = entry
    return out


def main(argv):
    text = json.dumps(build(), indent=2, sort_keys=False) + "\n"
    path = os.path.join(HERE, "libs.json")
    if "--check" in argv:
        try:
            same = open(path).read() == text
        except OSError:
            same = False
        print("libs.json is current" if same else "libs.json differs: run update_libs.py")
        return 0 if same else 1
    with open(path, "w") as f:
        f.write(text)
    print("wrote", path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
